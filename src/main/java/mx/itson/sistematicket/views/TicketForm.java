    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    try {
            Ticket data = new Ticket();
            data.setTitle(txtTitle.getText());
            data.setDescription(txtDescription.getText());
            data.setPriority((Priority) cmbPriority.getSelectedItem());
            Gson gson = new Gson();
            HttpRequest request;
            if (ticket == null) { // AGREGAR -> POST
                request = HttpRequest.newBuilder()
                    .uri(URI.create("http://127.0.0.1:8000/tickets/new"))
                    .header("Content-Type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(gson.toJson(data)))
                    .build();
            } else { // EDITAR -> PUT
                data.setStatus((Status) cmbStatus.getSelectedItem());
                request = HttpRequest.newBuilder()
                    .uri(URI.create("http://127.0.0.1:8000/tickets/" + ticket.getId()))
                    .header("Content-Type", "application/json")
                    .PUT(HttpRequest.BodyPublishers.ofString(gson.toJson(data)))
                    .build();
            }
            HttpClient client = HttpClient.newHttpClient();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
            TicketResponse result = gson.fromJson(response.body(), TicketResponse.class);
            JOptionPane.showMessageDialog(this, result.getMessage());
            if (result.isSuccess()) {
                dispose(); // cierra la ventana; Octavio recarga la tabla
            }
        } catch (IOException | InterruptedException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo conectar con la API");
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

